"""End-to-end test of every button in index.html (Playwright, Chromium, iPhone-sized viewport)."""
import functools, http.server, os, re, sys, threading, time
from playwright.sync_api import sync_playwright, expect

APP_DIR = sys.argv[1]
SHOTS = sys.argv[2]
os.makedirs(SHOTS, exist_ok=True)

handler = functools.partial(http.server.SimpleHTTPRequestHandler, directory=APP_DIR)
handler.log_message = lambda *a: None
srv = http.server.ThreadingHTTPServer(("127.0.0.1", 8765), handler)
threading.Thread(target=srv.serve_forever, daemon=True).start()
URL = "http://127.0.0.1:8765/index.html"

results, errors = [], []
def ok(name): results.append(("PASS", name)); print("PASS", name)
def check(cond, name):
    if cond: ok(name)
    else: results.append(("FAIL", name)); print("FAIL", name)

def shot(page, name): page.screenshot(path=f"{SHOTS}/{name}.png", full_page=True)
def act(page, a, nth=0): page.locator(f'[data-act="{a}"]').nth(nth).click()
def st(page, expr): return page.evaluate(f"() => {expr}")

with sync_playwright() as p:
    b = p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox"])
    ctx = b.new_context(viewport={"width": 390, "height": 844}, device_scale_factor=2, accept_downloads=True)
    page = ctx.new_page()
    page.on("console", lambda m: errors.append(f"console.{m.type}: {m.text}") if m.type in ("error", "warning") else None)
    page.on("pageerror", lambda e: errors.append(f"pageerror: {e}"))
    page.goto(URL); page.evaluate("localStorage.clear()"); page.reload()

