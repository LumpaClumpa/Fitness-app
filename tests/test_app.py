    expect(page.locator(".wk-title .t")).to_have_text("Legs B"); ok("Back to workout")
    act(page, "goFinish")
    hist = st(page, "state.history.length")
    act(page, "saveWorkout")
    expect(page.locator("#sumHead")).to_be_visible()
    hd = page.locator("#sumHead").inner_text()
