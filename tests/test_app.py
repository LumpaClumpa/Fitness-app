    page.locator("#height").fill("183"); page.locator("#weight").fill("82,5"); act(page, "onbBodyNext")
    check(st(page, "state.body.height") == 183 and st(page, "state.body.sex") == "male" and st(page, "state.body.weights[0].kg") == 82.5, "onboarding saves sex, height, weight")
