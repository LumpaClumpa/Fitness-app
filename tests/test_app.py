    page.locator('[data-act="restDefault"][data-d="-15"]').click(); page.locator('[data-act="restPreset"][data-v="180"]').click()
    check(st(page, "state.settings.rest.secs") == 180, "back to 3:00")
    page.locator('[data-act="cycleRest"]').first.click()
    check(st(page, "Object.keys(state.settings.rest.per).length") >= 1, "per-exercise rest set")
    page.locator('[data-act="cycleRest"]').first.click(); page.locator('[data-act="cycleRest"]').first.click()
    page.locator('[data-act="cycleRest"]').first.click(); page.locator('[data-act="cycleRest"]').first.click()
    page.locator('[data-act="cycleRest"]').first.click()
    check(st(page, "state.settings.rest.per['pendulum'] === undefined"), "per-exercise rest cycles back to Default")
    act(page, "restSound")
    check(st(page, "state.settings.rest.sound") is False, "sound toggle")
    act(page, "restSound")
    act(page, "restOn")
    check(st(page, "state.settings.rest.on") is False, "rest timer can be turned off")
    act(page, "restOn")
