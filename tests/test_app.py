    src = open(os.path.join(APP_DIR, "index.html"), encoding="utf-8").read()
    acts = set(re.findall(r'data-act="([A-Za-z]+)"', src)) | set(re.findall(r"data-act=\"\$\{([A-Za-z']+)", src))
    acts = {a for a in acts if not a.startswith("$") and a not in ("act", "state")}
    acts |= set(re.findall(r"switchHtml\([^,]+,\s*'([A-Za-z]+)'", src))
    missing = [a for a in acts if not st(page, f"typeof A['{a}'] === 'function'")]
    check(not missing, f"every data-act has a handler ({len(acts)} actions) {missing or ''}")

